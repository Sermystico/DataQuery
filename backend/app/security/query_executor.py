"""Database query executor using the restricted dq_readonly role.

================================================================================
SECURITY ARCHITECTURE & EXECUTION BOUNDARIES
================================================================================
This module serves as Layer 4 in DataQuery's defense-in-depth model:
1. Role Isolation:
   Executes ONLY through the SQLAlchemy `readonly_engine` bound to the `dq_readonly`
   PostgreSQL user. Never touches dq_owner or dq_app.
2. Trusted Type Invariant:
   Accepts ONLY `ValidatedSQL` instances generated by `validate_sql()`. Rejects raw
   strings or unvalidated query objects with a TypeError.
3. Transaction Scoping:
   Executes in a dedicated transaction with:
     - `SET TRANSACTION READ ONLY;`
     - `SET LOCAL statement_timeout = {QUERY_TIMEOUT_MS};`
4. Result Bounding:
   Fetches at most `max_rows + 1` rows to determine truncation safely without
   pulling unbounded result sets into application memory.
5. Error Sanitization:
   Never leaks raw SQL error traces or schema internals to the client. Logs detailed
   exceptions server-side and maps failures to typed AppErrors.
================================================================================
"""

import time
from dataclasses import dataclass
from typing import Any

import sqlalchemy as sa
from sqlalchemy.exc import OperationalError

from app.core.config import get_settings
from app.core.errors import AppError, DatabaseUnavailable, QueryTimeout
from app.core.logging import get_logger
from app.db.engines import readonly_engine
from app.security.sql_validator import ValidatedSQL

logger = get_logger("app.security.query_executor")


@dataclass(frozen=True)
class ExecutionResult:
    """Structured result of a read-only query execution."""

    columns: list[str]
    rows: list[list[Any]]
    truncated: bool
    duration_ms: float


def execute_query(
    validated_sql: ValidatedSQL,
    max_rows: int | None = None,
) -> ExecutionResult:
    """Execute a validated query within a restricted, read-only transaction.

    Args:
        validated_sql: Opaque token containing normalized and policy-checked SQL.
        max_rows: Optional row count limit override (defaults to MAX_RESULT_ROWS).

    Returns:
        ExecutionResult containing column names, row values, truncation flag, and timing.

    Raises:
        TypeError: If input is not a ValidatedSQL token.
        QueryTimeout: If statement duration exceeds QUERY_TIMEOUT_MS.
        DatabaseUnavailable: If connection to PostgreSQL fails.
        AppError: For any other database-side runtime error (sanitized).
    """
    if not isinstance(validated_sql, ValidatedSQL):
        raise TypeError(
            f"query_executor.execute_query() accepts only ValidatedSQL instances. "
            f"Received: {type(validated_sql).__name__}"
        )

    settings = get_settings()
    row_limit = max_rows if max_rows is not None else settings.MAX_RESULT_ROWS
    timeout_ms = settings.QUERY_TIMEOUT_MS

    start_time = time.perf_counter()

    try:
        with readonly_engine.connect() as conn:
            with conn.begin():
                # Enforce session/transaction-level invariants
                conn.execute(sa.text("SET TRANSACTION READ ONLY;"))
                conn.execute(sa.text(f"SET LOCAL statement_timeout = {int(timeout_ms)};"))

                # Execute statement
                cursor_result = conn.execute(sa.text(validated_sql.sql))

                columns = list(cursor_result.keys()) if cursor_result.returns_rows else []
                # Fetch up to row_limit + 1 to detect if results exceed the limit
                raw_rows = (
                    cursor_result.fetchmany(row_limit + 1) if cursor_result.returns_rows else []
                )

    except OperationalError as ex:
        duration_ms = (time.perf_counter() - start_time) * 1000.0
        err_str = str(ex).lower()
        logger.exception(
            "Operational error during read-only SQL execution (%.2fms): %s", duration_ms, ex
        )

        # 1. Statement Timeout check
        if (
            "statement timeout" in err_str
            or "canceling statement due to statement timeout" in err_str
        ):
            raise QueryTimeout(
                message="Database query cancelled: execution exceeded statement timeout.",
                details={"statement_timeout_ms": timeout_ms},
            ) from ex

        # 2. Connection Failure check
        if (
            "could not connect" in err_str
            or "connection refused" in err_str
            or "connection to server" in err_str
            or "server closed the connection" in err_str
        ):
            raise DatabaseUnavailable(
                message="Unable to establish connection to PostgreSQL engine.",
                details={"component": "database"},
            ) from ex

        # 3. Other Operational errors
        raise AppError(
            message="Database query execution error occurred.",
            code="DATABASE_ERROR",
            http_status=400,
        ) from ex

    except (DatabaseUnavailable, QueryTimeout):
        raise

    except Exception as ex:
        duration_ms = (time.perf_counter() - start_time) * 1000.0
        logger.exception(
            "Unexpected error during read-only SQL execution (%.2fms): %s", duration_ms, ex
        )
        raise AppError(
            message="Database query execution error occurred.",
            code="DATABASE_ERROR",
            http_status=400,
        ) from ex

    duration_ms = (time.perf_counter() - start_time) * 1000.0
    truncated = len(raw_rows) > row_limit
    final_rows = [list(row) for row in raw_rows[:row_limit]]

    return ExecutionResult(
        columns=columns,
        rows=final_rows,
        truncated=truncated,
        duration_ms=round(duration_ms, 2),
    )
